"""Developer tool for desktop widgets: scaffold a new one and list what is installed.

Widgets live in extension/widgets/: core/ ships with notheme, user/ is yours. Each widget is a
self-contained folder (widget.js for logic, widget.svg for its look); shared helpers are in lib/. user/index.js is regenerated from the files
in user/, so adding or deleting a folder there is all it takes.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WIDGETS = ROOT / 'extension/widgets'
USER = WIDGETS / 'user'
SIZES = ('1x1', '1x2', '2x1', '2x2', '3x1')
CATEGORIES = ('time', 'system', 'progress')

JS_TEMPLATE = '''// {name} widget: logic and data mapping. Its look is in widget.svg next to this file.
// Shared helpers are in ../../lib/; import only what you use, and never import another widget.
//
// Test it with `./notheme settings`: it appears under "Yours" in the widget browser.
import {{THEME}} from '../../lib/theme.js';
import {{square}} from '../../lib/charts.js';
import {{card}} from '../../lib/format.js';

// Shown in the widget browser. id: lowercase letters, digits and dashes, and the folder's name.
// size: columns x rows of grid units (1x1, 1x2, 2x1, 2x2 or 3x1).
export const meta = {{
    id: '{id}',
    name: '{name}',
    category: '{category}',
    kind: 'card',
    size: '{size}',
    description: 'Describe {name} in one line',
    author: '{author}',
}};

// Turn the latest `sample` (see extension/sampler.js: time, cpu, memory, disk, battery,
// temperature, uptime, cores, history) into plain data. `options` holds the user's choices
// (twelve, seconds, name, titles). Whatever you put in `chart` reaches vars() below.
export function build(sample, options) {{
    const hour = sample.time?.hour ?? 0;
    return card('{title}', '', {{chart: {{fraction: hour / 24, label: String(hour)}}}});
}}

// The drawing: size() picks the canvas shape, vars() maps the chart data to the values
// widget.svg uses. If the drawing is mostly logic, delete widget.svg and instead export
// `render(c, w, h, theme)` here, returning a whole SVG string (see svgDocument in ../../lib/svg.js). Besides your own values, the template can use the theme ({{{{bg}}}} {{{{fg}}}} {{{{dim}}}}
// {{{{muted}}}} {{{{line}}}} {{{{accent}}}} {{{{font}}}} {{{{mono}}}}), {{{{w}}}} {{{{h}}}}, {{{{square}}}} and {{{{uid}}}}.
// Values are re-read on every update, so animation is just a changing value.
export const chart = {{
    size: square(),
    vars(c) {{
        return {{angle: c.fraction * 360, fill: THEME.accent, label: c.label}};
    }},
}};
'''

SVG_TEMPLATE = '''<!-- {name}. Drawn in a fixed 100x100 box that scales to the card.
     Double braces insert a value from vars() in widget.js, triple braces insert SVG built there, and
     the if / each blocks branch and repeat (see lib/template.js for the full syntax). -->
<svg xmlns="http://www.w3.org/2000/svg" width="{{{{w}}}}" height="{{{{h}}}}" viewBox="0 0 100 100">
  <circle cx="50" cy="50" r="46" fill="none" stroke="{{{{line}}}}" stroke-width="1"/>
  <g transform="rotate({{{{angle}}}} 50 50)"><circle cx="50" cy="8" r="4" fill="{{{{accent}}}}"/></g>
  <text x="50" y="50" dy=".35em" fill="{{{{fg}}}}" font-family="{{{{font}}}}" font-weight="700" font-size="28" text-anchor="middle">{{{{label}}}}</text>
</svg>
'''


def camel(widget_id):
    return re.sub(r'-(\w)', lambda m: m.group(1).upper(), widget_id)


def ids(folder):
    return sorted(p.parent.name for p in folder.glob('*/widget.js'))


def meta_id(folder):
    match = re.search(r"^\s*id:\s*'([^']*)'|export const meta = \{id: '([^']*)'", (folder / 'widget.js').read_text(), re.M)
    return (match.group(1) or match.group(2)) if match else None


def reserved():
    """Ids a new widget may not take: every built-in id and the aliases of retired widgets."""
    names = set(ids(WIDGETS / 'core'))
    for path in (WIDGETS / 'core').glob('*/widget.js'):
        for match in re.finditer(r"aliases:\s*\[([^\]]*)\]", path.read_text()):
            names.update(re.findall(r"'([^']+)'", match.group(1)))
    return names


def write_user_index():
    names = ids(USER)
    seen = {}
    for n in names:
        declared = meta_id(USER / n)
        if declared != n:
            raise ValueError(f"user/{n}/widget.js declares id {declared!r}; it must match the folder name {n!r}")
        if declared in reserved():
            raise ValueError(f"user/{n}: id {declared!r} is already used by a built-in widget or alias")
    lines = ['// Your widgets. Regenerated by `./notheme widget new`; each entry has the same',
             "// shape as the folders in ../core/. Delete a widget's folder and run `./notheme widget sync`.\n"]
    lines += [f"import * as {camel(n)} from './{n}/widget.js';" for n in names]
    lines.append(('\n' if names else '') + f"export const USER_WIDGETS = [{', '.join(camel(n) for n in names)}];")
    (USER / 'index.js').write_text('\n'.join(lines) + '\n')


def git_author():
    try:
        return subprocess.run(['git', 'config', 'user.name'], capture_output=True, text=True, cwd=ROOT).stdout.strip()
    except OSError:
        return ''


def create(widget_id, name=None, category='system', size='1x1', author=None):
    if not re.fullmatch(r'[a-z][a-z0-9-]{0,30}', widget_id):
        raise ValueError('id must be lowercase letters, digits and dashes, starting with a letter')
    if widget_id in reserved() or widget_id in ids(USER):
        raise ValueError(f'a widget named {widget_id} already exists')
    if category not in CATEGORIES or size not in SIZES:
        raise ValueError(f'category is one of {CATEGORIES}; size is one of {SIZES}')
    name = name or widget_id.replace('-', ' ').title()
    USER.mkdir(parents=True, exist_ok=True)
    folder = USER / widget_id
    folder.mkdir()
    path = folder / 'widget.js'
    path.write_text(JS_TEMPLATE.format(id=widget_id, name=name.replace("'", ''), category=category,
                                       size=size, title=name.upper().replace("'", ''),
                                       author=(author if author is not None else git_author()).replace("'", '')))
    (folder / 'widget.svg').write_text(SVG_TEMPLATE.format(name=name.replace("'", '')))
    write_user_index()
    return path


def listing():
    rows = [('core', n) for n in ids(WIDGETS / 'core')] + [('user', n) for n in ids(USER)]
    return '\n'.join(f'{origin:5} {n}' for origin, n in rows)


def run(args):
    if args.action == 'new':
        path = create(args.id, args.name, args.category, args.size, args.author)
        print(f'Created {path.parent.relative_to(ROOT)}/ with widget.js and widget.svg\nPreview it with: ./notheme settings')
    elif args.action == 'sync':
        write_user_index()
        print('Updated extension/widgets/user/index.js')
    else:
        print(listing())
